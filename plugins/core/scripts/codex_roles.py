#!/usr/bin/env python3
"""Codex 门的角色生成器：`agents/*.md` → `.codex/roles/<role>.toml` ＋ `.codex/config.toml` 注册段
＋ 产物账本 `.workframe/managed-files.json`。`workframe_door.py` 是唯一调用方，本模块只管生成与账本。

**契约（实测、两版一致）**：Codex 的子 agent 角色注册在项目 `.codex/config.toml` 的
`[agents.<name>]` 段，正文**必须**经 `config_file` 指向外置 role TOML；把 `developer_instructions`
内联进注册段会被**静默丢弃**（能注册、能 spawn、就是没有正文）。role TOML 里的 `name` 会被丢弃，
名字 = 注册段的表名。所以产物是两样：4 个 role TOML ＋ 4 段两行的注册。

**产物形态**
  - `.codex/roles/<role>.toml`：首行 `# DO NOT EDIT` 头标（说明来源与定制入口），
    `developer_instructions = '''<agents/<role>.md 去 frontmatter 的正文>'''`。
  - 用户定制：`.codex/roles/<role>.local.toml` 里写 `developer_instructions = "…"`，生成时**追加**在
    正文之后（`\\n\\n---\\n\\n` 分隔）。定制文件永不被生成器写，不进账本。
  - `.codex/config.toml`：只维护 marker 之间的一段（形态同 `.gitignore` 的 managed block），
    **段外字节一律不动**（不归一换行、不删空行——用户自写的部分原样保留）。段首是本插件的
    **项目级启用表** `[plugins."core@<市场名>"] enabled = true`（装机器同时把用户层置 `false`，插件只在
    跑过装机的项目里加载），其后是各角色的 `[agents.<role>]`。起点：
      文件不存在 → 新建，整份就是 managed 段；
      存在、**无 marker**（用户自己写的 `.codex/config.toml`）→ 末尾追加 managed 段并入账——
        账本只记段内 sha，用户段不参与任何判断；
      有 marker 且在账本、段内 sha 相符 → 替换段内（无启用表的旧形态段同样按「未被手改」替换）；
      有 marker 且在账本、**段首启用表被改成 `enabled = false`、其余与账本一致** → 「用户已关本项目
        Codex 门」的合法态：不改回，**生成前拒绝**，文案说明要重新开启就把它改回 `true` 后重跑；
      有 marker 且在账本、段内**其他任何一行**被手改 → **生成前拒绝**；
      有 marker 但**不在账本** → 分不清段内是不是被手改过，**生成前拒绝、不写任何文件**
        （`RoleError`，文案给出路：恢复账本，或把 marker 连同段一起删掉后重跑）。
    `config_file` 写 **相对 `.codex/` 的路径** `roles/<role>.toml`——项目随仓走，不写绝对路径
    （Codex 对相对路径按哪个基准解析由装机器的 `config/read` 回读核对；核不出即报出来）。
  - 账本 `<project>/.workframe/managed-files.json`：记录写过的每个文件（相对项目根）与 sha256。
    **重生成只动账本内的**；role TOML 存在但不在账本内 → 跳过并告警（`config.toml` 的规则见上）；
    在账本内但内容与账本 sha 不同（被手改）→ 跳过并告警、不覆盖——覆盖等于删掉用户的改动，
    删除权不给程序。要重生成先把该文件恢复到账本记录的内容或自行删除。账本进 git 是有意的
    （它是共享核心，`.workframe/state/` 才是运行态）。
    **比对口径**：记账与每一处比对（被手改、无操作、账本要不要重写）都经 `sha256_bytes`，先把 CRLF 归一成
    LF——git 检出时把 LF 转成 CRLF 只改行尾、不改内容，只差行尾的文件不算被手改，也不重写、不重记账本。
  - **整份语义判定**（`whole_file_problem`，**唯一实现**：装机器写任何东西之前的 `preflight()`、
    `generate()` 落盘前、`verify()` 与 `--check` 都用它）：把段拼进当前文件文本，对**拼接后的整份候选**
    做 TOML 解析，要求段内声明的每张表（启用表、每个 `agents.<role>`）在整份文件里的值**恰好等于**
    段单独解析出的值。不满足时三种说法：段外有同名声明（两张同名表 Codex 拒绝加载整份项目配置）、
    段后内容被段内表吸收、当前文件本身解析不了。
    **能力边界**：写在 END marker 之后、没有表头的键，按 TOML 语义属于段内**最后一张表**——Codex 或整份
    拒载、或把用户的值静默吞进段内的表；只解析「段外文本」给不出整份文件的真实语义，所以判的是整份。
    段外子表 `[plugins."core@<市场名>".x]` 按同一判据拒绝——严格是有意的（段内那张表必须恰好只有
    `enabled`）；只声明了别的插件的 `[plugins."other@mkt"]` 不受影响。

**确定性**：同输入逐字节同输出（LF、键序固定、不含时间戳——时间戳只在账本的 `written_at`）。

被 CLI 以同目录 import 方式使用：模块 import 无副作用；文件名用下划线。
"""

